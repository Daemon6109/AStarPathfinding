import { Grid, AStar, Node, containsNode, getHeuristic, version } from "@rbxts/astar-pathfinding";
import type { Path } from "@rbxts/astar-pathfinding";
const grid = Grid({ width: 3, height: 3, blockProbability: 0 });
const solver = AStar({ grid });
const start = grid.getNode(1, 1)!;
const goal = grid.getNode(3, 3)!;
const path: Path | undefined = solver.findPath(1, 1, 3, 3);
assert(path !== undefined && path.size() === 3);
assert(path[0] === start && path[2] === goal);
assert(containsNode(path, start) && getHeuristic(start, goal) === 4);
assert(start.getFCost() === start.gCost + start.hCost);
assert(grid.getNeighbors(start).size() === 3);
assert(grid.getNode(0, 1) === undefined);
assert(solver.findPath(0, 1, 3, 3) === undefined);
goal.walkable = false;
assert(solver.findPath(1, 1, 3, 3) === undefined);
goal.walkable = true;
assert(solver.findPath(2, 2, 2, 2)!.size() === 1);
assert(Node({ x: 7, y: 8, walkable: false }).parent === undefined);
assert(version.major === 1);
const isolated = Grid({ width: 3, height: 3, blockProbability: 0 });
isolated.getNode(2, 1)!.walkable = false;
isolated.getNode(1, 2)!.walkable = false;
isolated.getNode(2, 2)!.walkable = false;
assert(AStar({ grid: isolated }).findPath(1, 1, 3, 3) === undefined);
assert(grid.grid.get(1)!.get(1) === start);
